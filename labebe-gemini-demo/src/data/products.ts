export const products: Record<string, Product> = Object.fromEntries(
  productList.map((product) => [product.slug, product]),
);

export const getProduct = (slug?: string) => (slug ? products[slug] : undefined);

export const getBestSellers = () =>
  productList
    .filter((product) => product.reviewCount !== null)
    .sort((a, b) => (b.reviewCount ?? 0) - (a.reviewCount ?? 0))
    .slice(0, 8);

export const getByWorld = (world: string) => productList.filter((product) => product.world === world);

export const getBundleProducts = (product: Product) =>
  product.bundleSlugs.map((slug) => products[slug]).filter(Boolean);

export const formatPrice = (price: number) => `$${price.toFixed(2)}`;

export const giftFinderRecommendations = (age: string, room: string, occasion: string) => {
  const scored = productList.map((product) => {
    let score = 0;
    if (age && product.ageRange.toLowerCase().includes(age.toLowerCase())) score += 3;
    if (room && product.roomTags.some((tag) => tag.toLowerCase() === room.toLowerCase())) score += 3;
    if (occasion && product.giftTags.some((tag) => tag.toLowerCase().includes(occasion.toLowerCase()))) score += 2;
    if (product.reviewCount) score += Math.min(product.reviewCount / 6, 2);
    return { product, score };
  });

  return scored
    .sort((a, b) => b.score - a.score)
    .slice(0, 3)
    .map(({ product }) => product);
};
